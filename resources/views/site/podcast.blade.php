            <section class="podcast-section">
                <h2 class="podcast-section-heading">1. Los bloqueos más comunes</h2>

                <p>
                    En los procesos creativos siempre aparecen obstáculos. No son una anomalía,
                    son parte del camino. Podemos agruparlos en tres niveles:
                </p>

                <dl class="podcast-list">
                    <dt>Bloqueo emocional</dt>
                    <dd>Cuando la ansiedad, la autocrítica o el ruido mental ocupan toda la atención.</dd>

                    <dt>Bloqueo creativo</dt>
                    <dd>Cuando la hoja en blanco se convierte en un muro y las ideas se repiten sin chispa.</dd>

                    <dt>Bloqueo estructural</dt>
                    <dd>Cuando hay demasiadas ideas y ninguna manera de priorizarlas ni transformarlas en acción.</dd>
                </dl>

                <p>Cada nivel exige una forma distinta de abordaje.</p>
            </section>

