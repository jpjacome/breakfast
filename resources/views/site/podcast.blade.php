            <section class="podcast-section">
                <h2 class="podcast-section-heading">3. Tres estrategias para romper bloqueos</h2>

                <h3 class="podcast-strategy-heading">
                    Morning Pages — Julia Cameron, <cite>The Artist’s Way</cite> (1992)
                </h3>

                <dl class="podcast-list">
                    <dt>Bloqueo que resuelve</dt>
                    <dd>El emocional.</dd>

                    <dt>Función</dt>
                    <dd>Vaciar la mente para recuperar claridad y confianza.</dd>

                    <dt>Cómo funciona</dt>
                    <dd>
                        Escribir tres páginas cada mañana, sin filtro, para drenar pensamientos
                        repetitivos, miedos o pendientes.
                    </dd>

                    <dt>Resultado</dt>
                    <dd>
                        Una mente más ligera, menos ruido interno y mayor foco al empezar la
                        jornada creativa.
                    </dd>
                </dl>

                <h3 class="podcast-strategy-heading">
                    Oblique Strategies — Brian Eno &amp; Peter Schmidt (1975)
                </h3>

                <dl class="podcast-list">
                    <dt>Bloqueo que resuelve</dt>
                    <dd>El creativo.</dd>

                    <dt>Función</dt>
                    <dd>Romper bucles de pensamiento y activar el pensamiento lateral.</dd>

                    <dt>Cómo funciona</dt>
                    <dd>
                        Se toma una carta con una frase enigmática, como “Honra tu error como una
                        intención oculta”, “Usa una idea vieja” o “¿Qué haría tu mejor amigo?”, y
                        se aplica literalmente o como metáfora.
                    </dd>

                    <dt>Resultado</dt>
                    <dd>
                        Ruptura inmediata del bloqueo, apertura a nuevas conexiones y generación
                        de ideas frescas.
                    </dd>
                </dl>

                <h3 class="podcast-strategy-heading">
                    Design Methods — John Chris Jones (1970)
                </h3>

                <dl class="podcast-list">
                    <dt>Bloqueo que resuelve</dt>
                    <dd>El estructural.</dd>

                    <dt>Función</dt>
                    <dd>Organizar y transformar lo disperso en propuestas accionables.</dd>

                    <dt>Cómo funciona</dt>
                    <dd>
                        A través de métodos como <em>Randomization</em>, <em>Inversion</em> y,
                        sobre todo, <em>System Mapping</em>.
                    </dd>
                </dl>

                <dl class="podcast-list">
                    <dt>Randomization</dt>
                    <dd>
                        Introducir un elemento externo al azar, como una palabra o imagen, para
                        forzar conexiones nuevas.
                    </dd>

                    <dt>Inversion</dt>
                    <dd>
                        Plantear el reto en su versión contraria y descubrir criterios de mejora
                        al revertir las respuestas.
                    </dd>

                    <dt>System Mapping</dt>
                    <dd>
                        Representar todos los elementos de un reto en un mapa: actores, procesos,
                        productos, canales. Las conexiones muestran dependencias y revelan
                        patrones invisibles. En el caso de una cafetería, el mapa muestra que la
                        atmósfera y la logística pesan tanto como el café mismo. Esa visión
                        permite priorizar acciones y decidir dónde intervenir con mayor impacto.
                    </dd>
                </dl>
            </section>

            <section class="podcast-section">
                <h2 class="podcast-section-heading">Profundizando en System Mapping</h2>

                <p>
                    Imagina un proyecto de una cafetería. Si piensas solo en el café, te quedas en
                    lo obvio. El mapeo obliga a incluir al cliente, al barista, al menú, al
                    mobiliario, a la música, al delivery, a las reseñas en redes. Todo entra en el
                    mismo plano. Luego trazas conexiones: cliente ↔ barista, menú ↔ percepción de
                    valor, delivery ↔ reputación online.
                </p>

                <p>
                    De pronto aparecen patrones invisibles: el ambiente pesa más que el café, el
                    delivery puede dañar la experiencia sin que nadie cruce la puerta, el menú es
                    el primer filtro antes de probar el producto. Ese mapa convierte un problema
                    genérico (“mejorar la experiencia”) en una radiografía precisa de dónde
                    intervenir primero.
                </p>

                <dl class="podcast-list">
                    <dt>Resultado</dt>
                    <dd>
                        Foco. Se identifican puntos de impacto concretos, se jerarquizan acciones
                        y se elimina la sensación de estar atrapado en un mar de ideas sin
                        conexión.
                    </dd>
                </dl>
            </section>

